-- Overview:
-- This file extends the existing Collider DB database by adding
-- Three new tables to support the trigger reasons and flag event
--
-- The original database tables are kept unchanged.
-- This file also includes sample data for the newly created tables.
--
-- New Tables:
-- 1. Trigger
-- 2. event_trigger
-- 3. flag_review


USE collider_db;

SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS flag_event;
DROP TABLE IF EXISTS event_trigger;
DROP TABLE IF EXISTS trigger;
SET FOREIGN_KEY_CHECKS = 1;

-- 1. Trigger definitions

CREATE TABLE trigger (
  trigger_id INT NOT NULL AUTO_INCREMENT,
  trigger_name VARCHAR(100) NOT NULL,
  trigger_type VARCHAR(50) NOT NULL,
  threshold_energy DOUBLE DEFAULT NULL,
  description TEXT,
  status VARCHAR(30) NOT NULL DEFAULT 'Active',
  PRIMARY KEY (trigger_id)
) ENGINE=InnoDB
  
-- 2. Many-to-many / junction log between collision events and triggers
  
CREATE TABLE event_trigger (
  event_trigger_id INT NOT NULL AUTO_INCREMENT,
  event_id INT NOT NULL,
  trigger_id INT NOT NULL,
  trigger_timestamp DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  trigger_result VARCHAR(50) NOT NULL,
  PRIMARY KEY (event_trigger_id),
  CONSTRAINT fk_event_trigger_event
    FOREIGN KEY (event_id) REFERENCES collisionevent (event_id)
    ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_event_trigger_trigger
    FOREIGN KEY (trigger_id) REFERENCES trigger (trigger_id)
    ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB 

-- 3. Flagged collision events review queue
  
CREATE TABLE IF NOT EXISTS flag_review (
  review_id INT NOT NULL AUTO_INCREMENT,
  flag_id INT NOT NULL,
  reviewer_id INT NOT NULL,
  review_status VARCHAR(30) NOT NULL DEFAULT 'Pending',
  review_reason` VARCHAR(255) DEFAULT NULL,
  reviewed_at DATETIME DEFAULT NULL,
  remarks TEXT,
  PRIMARY KEY (review_id),
  CONSTRAINT fk_flag_review_flag
    FOREIGN KEY (flag_id) REFERENCES flaggedevent (`flag_id`)
    ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_flag_review_reviewer
    FOREIGN KEY (reviewer_id) REFERENCES researcher (researcher_id)
    ON DELETE RESTRICT ON UPDATE CASCADE
) ENGINE=InnoDB 

